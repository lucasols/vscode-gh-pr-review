import * as vscode from 'vscode'
import { config } from '../config'
import { fromDocUri } from '../content/ghprFs'
import { docRefPrKey } from '../content/docRef'
import { isChangedSinceViewed } from '../model/baselines'
import {
  CHANGE_KIND_LABELS,
  type NonRelevantChangeKind,
} from '../model/changeClassifier'
import {
  buildFileList,
  buildFileTree,
  flattenFiles,
  type FileTreeNode,
} from '../model/fileTree'
import type { PrDetail, PrFile } from '../model/types'
import type { Services } from '../services'
import { debounce } from '../util/async'
import { toTreeFileUri } from './decorations'
import { getLocalFileUri } from './diffOpener'
import { warnAboutLocalChanges } from './localChanges'

export type ChangesNode =
  | { kind: 'description'; prKey: string }
  | { kind: 'pendingReview'; prKey: string; count: number }
  | { kind: 'folder'; prKey: string; path: string; name: string; children: ChangesNode[] }
  | { kind: 'file'; prKey: string; path: string; name: string; file: PrFile }

const CHANGE_KIND_TOOLTIPS: Record<NonRelevantChangeKind, string> = {
  lockfile: 'Generated by a package manager.',
  renameOnly: 'The file was renamed and its content did not change.',
  importsOnly: 'Only import statements changed.',
}

const nodeRegistry = new WeakSet<object>()

export function isChangesNode(value: unknown): value is ChangesNode {
  return typeof value === 'object' && value !== null && nodeRegistry.has(value)
}

export function collectNodePaths(node: ChangesNode): string[] {
  if (node.kind === 'file') return [node.path]
  if (node.kind === 'folder') return node.children.flatMap(collectNodePaths)
  return []
}

function nodeId(node: ChangesNode): string {
  switch (node.kind) {
    case 'description':
      return `${node.prKey}|description`
    case 'pendingReview':
      return `${node.prKey}|pendingReview`
    case 'folder':
      return `${node.prKey}|folder|${node.path}`
    case 'file':
      return `${node.prKey}|file|${node.path}`
  }
}

/**
 * The tree of the changed files of the focused pull request.
 *
 * It is rebuilt from the store on every change and every node has a stable
 * id, so VS Code keeps the expanded folders, the selection and the scroll
 * position. Nothing is loaded while the tree is rendered.
 */
export class ChangesView implements vscode.TreeDataProvider<ChangesNode>, vscode.Disposable {
  private readonly emitter = new vscode.EventEmitter<void>()
  readonly onDidChangeTreeData = this.emitter.event

  private readonly treeView: vscode.TreeView<ChangesNode>
  private readonly subscriptions: vscode.Disposable[] = []
  private readonly rebuildSoon = debounce(() => this.rebuild(), 30)

  private roots: ChangesNode[] = []
  private readonly parents = new Map<ChangesNode, ChangesNode>()
  private readonly fileNodes = new Map<string, ChangesNode>()
  private orderedFiles: PrFile[] = []

  constructor(private readonly services: Services) {
    this.treeView = vscode.window.createTreeView('ghPrReview.changes', {
      treeDataProvider: this,
      showCollapseAll: true,
      manageCheckboxStateManually: true,
    })

    const { store, classifier } = services
    this.subscriptions.push(
      this.treeView,
      this.emitter,
      store.onDidChangeFocus(() => this.rebuildSoon.call()),
      store.onDidChangeDetail((key) => {
        if (key === store.focusedKey) this.rebuildSoon.call()
      }),
      store.onDidChangeLists(() => this.rebuildSoon.call()),
      classifier.onDidChange((key) => {
        if (key === store.focusedKey) this.rebuildSoon.call()
      }),
      vscode.workspace.onDidChangeConfiguration((event) => {
        if (
          config.affects(event, 'fileLayout') ||
          config.affects(event, 'hideViewedFiles') ||
          config.affects(event, 'defaultDiff')
        ) {
          this.rebuild()
        }
      }),
      this.treeView.onDidChangeCheckboxState((event) => this.onCheckboxChange(event)),
      vscode.window.onDidChangeActiveTextEditor((editor) => this.revealEditor(editor)),
    )

    this.rebuild()
  }

  /** The files of the focused pull request in the order that they are shown */
  getOrderedFiles(): readonly PrFile[] {
    return this.orderedFiles
  }

  private onCheckboxChange(event: vscode.TreeCheckboxChangeEvent<ChangesNode>): void {
    const groups = new Map<string, { prKey: string; viewed: boolean; paths: string[] }>()
    for (const [node, state] of event.items) {
      if (node.kind !== 'file' && node.kind !== 'folder') continue
      const viewed = state === vscode.TreeItemCheckboxState.Checked
      const groupKey = `${node.prKey}|${viewed}`
      let group = groups.get(groupKey)
      if (!group) {
        group = { prKey: node.prKey, viewed, paths: [] }
        groups.set(groupKey, group)
      }
      group.paths.push(...collectNodePaths(node))
    }
    for (const group of groups.values()) {
      if (group.viewed) {
        void warnAboutLocalChanges(this.services, group.prKey, group.paths)
      }
      void this.services.store.setViewed(group.prKey, group.paths, group.viewed)
    }
  }

  private rebuild(): void {
    const { store } = this.services
    const prKey = store.focusedKey
    const detail = prKey ? store.getDetail(prKey) : undefined

    this.roots = []
    this.parents.clear()
    this.fileNodes.clear()
    this.orderedFiles = []

    if (!prKey) {
      this.treeView.title = 'Changes'
      this.treeView.description = undefined
      this.treeView.badge = undefined
      this.treeView.message = undefined
      this.emitter.fire()
      return
    }

    const summary = detail?.summary ?? store.findSummary(prKey)
    const number = prKey.slice(prKey.lastIndexOf('#') + 1)
    this.treeView.title = `Changes in #${number}`
    this.treeView.description = summary?.title

    if (!detail) {
      const error = store.getDetailError(prKey)
      this.treeView.message = error ? `Could not load the pull request: ${error}` : 'Loading…'
      this.treeView.badge = undefined
      this.emitter.fire()
      return
    }

    const error = store.getDetailError(prKey)
    const unviewed = detail.files.filter((file) => file.viewedState !== 'VIEWED')
    const hideViewed = config.hideViewedFiles()

    const messages: string[] = []
    if (error) messages.push(`Could not refresh: ${error}`)
    if (hideViewed && unviewed.length === 0 && detail.files.length > 0) {
      messages.push(`All ${detail.files.length} files are viewed.`)
    } else if (hideViewed && unviewed.length < detail.files.length) {
      messages.push(`${detail.files.length - unviewed.length} viewed files are hidden.`)
    }
    this.treeView.message = messages.length > 0 ? messages.join(' ') : undefined
    this.treeView.badge =
      unviewed.length > 0 ?
        {
          value: unviewed.length,
          tooltip: `${unviewed.length} of ${detail.files.length} files left to view in #${number}`,
        }
      : undefined

    const register = <T extends ChangesNode>(node: T): T => {
      nodeRegistry.add(node)
      return node
    }

    this.roots.push(register({ kind: 'description', prKey }))
    if (detail.pendingReview) {
      this.roots.push(
        register({
          kind: 'pendingReview',
          prKey,
          count: detail.pendingReview.commentCount,
        }),
      )
    }

    const visibleFiles = hideViewed ? unviewed : detail.files
    const tree: FileTreeNode<PrFile>[] =
      config.fileLayout() === 'list' ?
        buildFileList(visibleFiles)
      : buildFileTree(visibleFiles, { compact: true })
    this.orderedFiles = flattenFiles(tree)

    const convert = (node: FileTreeNode<PrFile>, parent: ChangesNode | undefined) => {
      let result: ChangesNode
      if (node.kind === 'file') {
        result = register({
          kind: 'file',
          prKey,
          path: node.path,
          name: node.name,
          file: node.file,
        })
        this.fileNodes.set(node.path, result)
      } else {
        const folder: ChangesNode = register({
          kind: 'folder',
          prKey,
          path: node.path,
          name: node.name,
          children: [],
        })
        folder.children = node.children.map((child) => convert(child, folder))
        result = folder
      }
      if (parent) this.parents.set(result, parent)
      return result
    }
    for (const node of tree) this.roots.push(convert(node, undefined))

    this.emitter.fire()
  }

  getChildren(node?: ChangesNode): ChangesNode[] {
    if (!node) return this.roots
    return node.kind === 'folder' ? node.children : []
  }

  getParent(node: ChangesNode): ChangesNode | undefined {
    return this.parents.get(node)
  }

  getTreeItem(node: ChangesNode): vscode.TreeItem {
    switch (node.kind) {
      case 'description': {
        const item = new vscode.TreeItem('Description')
        item.id = nodeId(node)
        item.iconPath = new vscode.ThemeIcon('git-pull-request')
        item.command = {
          command: 'ghPrReview.openDescription',
          title: 'Open Pull Request Description',
          arguments: [node.prKey],
        }
        return item
      }

      case 'pendingReview': {
        const item = new vscode.TreeItem('Pending review')
        item.id = nodeId(node)
        item.description = `${node.count} ${node.count === 1 ? 'comment' : 'comments'} not submitted`
        item.iconPath = new vscode.ThemeIcon('comment-draft')
        item.contextValue = 'pendingReview'
        item.command = {
          command: 'ghPrReview.submitReview',
          title: 'Submit Review…',
          arguments: [node.prKey],
        }
        return item
      }

      case 'folder': {
        const item = new vscode.TreeItem(
          node.name,
          vscode.TreeItemCollapsibleState.Expanded,
        )
        item.id = nodeId(node)
        const detail = this.services.store.getDetail(node.prKey)
        const paths = new Set(collectNodePaths(node))
        const files = detail?.files.filter((file) => paths.has(file.path)) ?? []
        const allViewed =
          files.length > 0 && files.every((file) => file.viewedState === 'VIEWED')
        item.checkboxState = {
          state:
            allViewed ?
              vscode.TreeItemCheckboxState.Checked
            : vscode.TreeItemCheckboxState.Unchecked,
          tooltip: allViewed ? 'Mark all as not viewed' : 'Mark all as viewed',
        }
        item.contextValue = `folder ${allViewed ? 'viewed' : 'unviewed'}`
        item.tooltip = node.path
        return item
      }

      case 'file':
        return this.getFileItem(node, this.services.store.getDetail(node.prKey))
    }
  }

  private getFileItem(
    node: Extract<ChangesNode, { kind: 'file' }>,
    detail: PrDetail | undefined,
  ): vscode.TreeItem {
    const { store, classifier } = this.services
    const { file } = node
    const baseline = store.getBaselines(node.prKey)[file.path]
    const changedSinceViewed = isChangedSinceViewed(file, baseline)
    const isViewed = file.viewedState === 'VIEWED'
    const sinceViewedIsDefault = changedSinceViewed && config.defaultDiff() === 'sinceViewed'

    const item = new vscode.TreeItem(
      toTreeFileUri(file.path, file.status, changedSinceViewed),
    )
    item.id = nodeId(node)
    item.label = node.name
    item.checkboxState = {
      state:
        isViewed ?
          vscode.TreeItemCheckboxState.Checked
        : vscode.TreeItemCheckboxState.Unchecked,
      tooltip: isViewed ? 'Mark as not viewed' : 'Mark as viewed',
    }
    item.command = {
      command: 'ghPrReview.openFile',
      title: 'Open Changes',
      arguments: [node.prKey, file.path],
    }

    const kind =
      !isViewed && detail ? classifier.classify(detail, file, baseline) : undefined
    const nonRelevant = kind !== undefined && kind !== 'relevant' ? kind : undefined
    const comments =
      detail?.threads.filter((thread) => thread.path === file.path && !thread.isResolved)
        .length ?? 0

    const description: string[] = []
    if (config.fileLayout() === 'list') {
      const folder = file.path.slice(0, Math.max(0, file.path.lastIndexOf('/')))
      if (folder) description.push(folder)
    }
    if (changedSinceViewed) description.push('changed since viewed')
    if (nonRelevant) description.push(CHANGE_KIND_LABELS[nonRelevant])
    if (comments > 0) description.push(`${comments} ${comments === 1 ? 'comment' : 'comments'}`)
    item.description = description.join(' · ')

    const tooltip = new vscode.MarkdownString()
    tooltip.appendText(file.path)
    if (file.previousPath) tooltip.appendText(`\nRenamed from ${file.previousPath}`)
    tooltip.appendText(`\n+${file.additions} −${file.deletions}`)
    if (changedSinceViewed) {
      tooltip.appendText(
        sinceViewedIsDefault ?
          '\nChanged after you viewed it. Opens with only the changes made since then.'
        : '\nChanged after you viewed it.',
      )
    }
    if (nonRelevant) tooltip.appendText(`\n${CHANGE_KIND_TOOLTIPS[nonRelevant]}`)
    item.tooltip = tooltip

    const flags = ['file', isViewed ? 'viewed' : 'unviewed']
    if (baseline) flags.push('baseline')
    if (changedSinceViewed) {
      flags.push(sinceViewedIsDefault ? 'sinceViewedDefault' : 'fullDefault')
    }
    if (file.status !== 'removed' && store.getRepoForPr(node.prKey)) flags.push('local')
    item.contextValue = flags.join(' ')

    return item
  }

  /** Selects the file of the active editor in the tree */
  private revealEditor(editor: vscode.TextEditor | undefined): void {
    if (!editor || !this.treeView.visible) return
    const prKey = this.services.store.focusedKey
    if (!prKey) return

    const uri = editor.document.uri
    let path: string | undefined
    const ref = fromDocUri(uri)
    if (ref) {
      if (docRefPrKey(ref) === prKey) path = ref.path
    } else if (uri.scheme === 'file') {
      for (const candidate of this.fileNodes.keys()) {
        if (getLocalFileUri(this.services, prKey, candidate)?.fsPath === uri.fsPath) {
          path = candidate
          break
        }
      }
    }

    const node = path ? this.fileNodes.get(path) : undefined
    if (!node) return
    void this.treeView.reveal(node, { select: true, focus: false }).then(
      () => undefined,
      () => undefined,
    )
  }

  dispose(): void {
    this.rebuildSoon.cancel()
    for (const subscription of this.subscriptions) subscription.dispose()
  }
}
